"""
Data Schemas for Multi-Agent Decision Coordination System.
Defines data structures for agent recommendations, shared system constraints,
and arbitration execution decisions.
"""

from dataclasses import dataclass, field
from enum import Enum
from typing import Dict, Any, List, Optional
import time


class ExecutionTier(Enum):
    AUTO_EXECUTE = "AUTO_EXECUTE"      # High confidence, low risk -> Act autonomously
    AUTO_LOG = "AUTO_LOG"              # Medium-high confidence -> Act and log audit trail
    ESCALATE = "ESCALATE"              # Low confidence or high financial risk -> Ask owner


class AgentType(Enum):
    FINANCE = "FINANCE"
    INVENTORY = "INVENTORY"
    CUSTOMER = "CUSTOMER"
    COMPLIANCE = "COMPLIANCE"
    GROWTH = "GROWTH"


@dataclass
class Recommendation:
    """
    Standardized schema for recommendations issued by domain agents.
    """
    recommendation_id: str
    agent_type: AgentType
    title: str
    description: str
    required_cash: float           # Financial capital required (in INR)
    urgency_score: float           # Scale 0.0 to 1.0 (1.0 = immediate deadline/loss)
    expected_roi_or_impact: float  # Scale 0.0 to 1.0
    risk_score: float              # Scale 0.0 to 1.0 (higher = riskier action)
    deadline_days: float           # Time left before opportunity/penalty expires
    metadata: Dict[str, Any] = field(default_factory=dict)
    timestamp: float = field(default_factory=time.time)


@dataclass
class SystemState:
    """
    Shared resource constraints across all agents in the business context.
    """
    available_cash: float          # Available liquid working capital (in INR)
    time_window_days: float        # Active operational window being evaluated
    credit_limit_available: float = 0.0  # Emergency credit buffer if applicable


@dataclass
class ArbitrationResult:
    """
    Final decision output generated by the Arbitration Engine.
    """
    arbitration_id: str
    approved_recommendations: List[Recommendation]
    rejected_recommendations: List[Recommendation]
    total_cash_allocated: float
    remaining_cash: float
    execution_tier: ExecutionTier
    decision_rationale: str
    priority_scores: Dict[str, float]


class DecisionStatus(Enum):
    APPROVED = "APPROVED"
    MODIFIED_CAP = "MODIFIED_CAP"
    REJECTED_LIQUIDITY = "REJECTED_LIQUIDITY"
    HELD_IN_AUDIT = "HELD_IN_AUDIT"


@dataclass
class RoutedDecision:
    decision_id: str
    recommendation: Recommendation
    approved_amount: float
    status: DecisionStatus
    reasoning: str

